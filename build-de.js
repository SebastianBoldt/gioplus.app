// Generates de/index.html from index.html and the DE table in i18n.js.
// Usage: node build-de.js   (no dependencies)
//
// index.html is the English page and the source of truth for markup.
// This script fills every data-i18n element and data-i18n-attr attribute with German,
// and adjusts the head (lang, title, description, canonical, Open Graph).

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = __dirname;
const I18N = vm.runInNewContext(fs.readFileSync(path.join(root, 'i18n.js'), 'utf8') + '; I18N', {});
const DE = I18N.tables.DE;
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const missing = new Set();
const de = key => {
    if (key in DE) return DE[key];
    missing.add(key);
    return null;
};
const attr = text => text.replace(/&/g, '&amp;').replace(/"/g, '&quot;');

// Element text. data-i18n elements never contain a child with the same tag name.
html = html.replace(/<(\w+)([^>]*\bdata-i18n="([^"]+)"[^>]*)>([\s\S]*?)<\/\1>/g, (all, tag, attrs, key, inner) => {
    const text = de(key);
    return text === null ? all : `<${tag}${attrs}>${text}</${tag}>`;
});

// Attributes: data-i18n-attr="alt:key;aria-label:key"
html = html.replace(/<(\w+)([^>]*\bdata-i18n-attr="([^"]+)"[^>]*)>/g, (all, tag, attrs, spec) => {
    let out = attrs;
    spec.split(';').forEach(pair => {
        const [name, key] = pair.split(':');
        const text = de(key);
        if (text !== null) out = out.replace(new RegExp(`(\\s${name}=")[^"]*(")`), `$1${attr(text)}$2`);
    });
    return `<${tag}${out}>`;
});

// Head
const swap = (from, to) => {
    if (!html.includes(from)) throw new Error('Not found in index.html: ' + from);
    html = html.replace(from, to);
};
const content = (selector, text) => {
    const pattern = new RegExp(`(<meta ${selector} content=")[^"]*(")`);
    if (!pattern.test(html)) throw new Error('Meta tag not found: ' + selector);
    html = html.replace(pattern, `$1${attr(text)}$2`);
};
swap('<html lang="en"', '<html lang="de"');
html = html.replace(/<title>[\s\S]*?<\/title>/, `<title>${DE['meta.title'].replace(/&/g, '&amp;')}</title>`);
content('name="description"', DE['meta.description']);
content('property="og:title"', DE['meta.ogTitle']);
content('property="og:description"', DE['meta.ogDescription']);
content('name="twitter:title"', DE['meta.ogTitle']);
content('name="twitter:description"', DE['meta.ogDescription']);
content('property="og:locale"', 'de_DE');
content('property="og:url"', 'https://gioplus.app/de/');
swap('<link rel="canonical" href="https://gioplus.app/">', '<link rel="canonical" href="https://gioplus.app/de/">');

// German screenshots from the first paint
html = html.replace(/\/media\/screens\/light-en-/g, '/media/screens/light-de-');

// Language switch
swap('<a href="/" data-lang="en" hreflang="en" aria-current="true">EN</a>', '<a href="/" data-lang="en" hreflang="en">EN</a>');
swap('<a href="/de/" data-lang="de" hreflang="de">DE</a>', '<a href="/de/" data-lang="de" hreflang="de" aria-current="true">DE</a>');

html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by build-de.js from index.html and i18n.js. Do not edit by hand. -->');

fs.mkdirSync(path.join(root, 'de'), { recursive: true });
fs.writeFileSync(path.join(root, 'de', 'index.html'), html);
console.log('de/index.html written');
if (missing.size) console.log('No German text for (left in English):', [...missing].join(', '));
